import { launch, check, note, finish } from './lib.mjs';
const g = await launch({ lang: 'vi', w: 1280, h: 720 });
const { page, ev, wait, click, exists, shot } = g;
await page.goto('http://127.0.0.1:4173/');
await page.waitForSelector('[data-testid="main-menu"]', { timeout: 180000 });
await ev(() => document.fonts.ready); await wait(1500);
const fam = (sel) => ev((sel) => { const el = document.querySelector(sel); return el ? getComputedStyle(el).fontFamily.split(',')[0].replace(/["']/g, '') : null; }, sel);
const loaded = () => ev(() => [...document.fonts].filter((f) => f.status === 'loaded').map((f) => `${f.family.replace(/["']/g, '')} ${f.style} ${f.weight} ${f.unicodeRange.startsWith('U+0-FF') || f.unicodeRange.startsWith('U+0000') ? 'latin' : 'vi'}`).sort());
const overflow = (sel) => ev((sel) => [...document.querySelectorAll(sel)].filter((el) => el.scrollWidth > el.clientWidth + 1 && getComputedStyle(el).overflowX === 'visible').map((el) => `${el.className || el.tagName}: ${el.textContent.slice(0, 40)}`).slice(0, 8), sel);
check('menu title uses Chakra Petch', (await fam('.menu h1')) === 'Chakra Petch', await fam('.menu h1'));
check('menu body uses Be Vietnam Pro', (await fam('body')) === 'Be Vietnam Pro', await fam('body'));
check('menu eyebrow uses JetBrains Mono', (await fam('.menu-eyebrow')) === 'JetBrains Mono', await fam('.menu-eyebrow'));
let L = await loaded(); note('loaded on menu: ' + L.join(' | '));
check('Chakra Petch Vietnamese + Latin faces loaded on the Vietnamese menu', L.some((x) => x.startsWith('Chakra Petch') && x.endsWith('vi')) && L.some((x) => x.startsWith('Chakra Petch') && x.endsWith('latin')));
check('Be Vietnam Pro Vietnamese face loaded', L.some((x) => x.startsWith('Be Vietnam Pro') && x.endsWith('vi')));
let o = await overflow('.menu *'); check('no clipped text in the menu (vi)', o.length === 0, o.join(' ; '));
await shot('font-menu-vi');
await click('menu-guide'); await page.waitForSelector('[data-testid="guide-panel"]', { timeout: 30000 }); await wait(800);
const firstCard = await ev(() => document.querySelector('[data-testid^="species-card-"]').getAttribute('data-testid'));
await click(firstCard); await wait(1200);
check('species heading uses Chakra Petch', (await fam('[data-testid="species-name"]')) === 'Chakra Petch', await fam('[data-testid="species-name"]'));
const sci = await ev(() => { const el = document.querySelector('[data-testid="species-scientific"]'); const cs = getComputedStyle(el); return `${cs.fontFamily.split(',')[0]} ${cs.fontStyle}`; });
check('scientific name is Chakra Petch italic', /Chakra Petch.* italic/.test(sci), sci);
await ev(() => document.fonts.ready); await wait(600);
L = await loaded();
check('a real italic face is loaded (no synthetic slant)', L.some((x) => x.startsWith('Chakra Petch italic')), L.filter((x) => x.includes('italic')).join(' | '));
o = await overflow('[data-testid="guide-panel"] *'); check('no clipped text in the field guide (vi)', o.length === 0, o.join(' ; '));
await shot('font-guide-vi');
await ev(() => document.querySelector('[data-testid="lang-en"]')?.click()); await wait(600);
o = await overflow('[data-testid="guide-panel"] *'); check('no clipped text in the field guide (en)', o.length === 0, o.join(' ; '));
await shot('font-guide-en');
await ev(() => document.querySelector('[data-testid="lang-vi"]')?.click()); await wait(400);
await g.startGame('biologist'); await wait(4000);
check('biome label uses Chakra Petch', (await fam('.biome')) === 'Chakra Petch', await fam('.biome'));
check('compass uses JetBrains Mono', (await fam('.compass-tick')) === 'JetBrains Mono', await fam('.compass-tick'));
o = await overflow('[data-testid="hud"] *'); o = o.filter((x) => !x.startsWith('compass-strip')); // the compass strip scrolls inside a clipped window by design
check('no clipped text in the HUD (vi)', o.length === 0, o.join(' ; '));
await shot('font-hud-vi');
await page.keyboard.press('KeyC'); await wait(3500);
await shot('font-camera-vi');
await page.keyboard.press('KeyC'); await wait(1500);
await page.keyboard.press('KeyJ'); await wait(3000);
o = await overflow('.panel *'); check('no clipped text in the journal (vi)', o.length === 0, o.join(' ; '));
await shot('font-journal-vi');
L = await loaded(); note('loaded at end: ' + L.join(' | '));
check('no failed requests', g.diag.failed.length === 0, g.diag.failed.slice(0, 3).join(' '));
check('no console errors', g.diag.errors.length === 0, g.diag.errors.slice(0, 2).join(' | '));
finish('fonts', g.diag);
await g.browser.close();
